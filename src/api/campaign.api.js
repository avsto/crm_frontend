import api from "./axios";

// ====================================================
// CAMPAIGN API
// ====================================================

const campaignApi = {
  // --------------------------------------------------
  // CREATE
  // --------------------------------------------------

  createCampaign: (data) => api.post("/campaigns", data),

  // --------------------------------------------------
  // GET ALL CAMPAIGNS
  // --------------------------------------------------

  getCampaigns: (params = {}) =>
    api.get("/campaigns", {
      params,
    }),

  // --------------------------------------------------
  // GET SINGLE CAMPAIGN
  // --------------------------------------------------

  getCampaignById: (id) => api.get(`/campaigns/${id}`),

  // --------------------------------------------------
  // UPDATE
  // --------------------------------------------------

  updateCampaign: (id, data) => api.put(`/campaigns/${id}`, data),

  // --------------------------------------------------
  // SCHEDULE
  // --------------------------------------------------

  scheduleCampaign: (id, scheduledAt) =>
    api.post(`/campaigns/${id}/schedule`, {
      scheduledAt,
    }),

  // --------------------------------------------------
  // PAUSE
  // --------------------------------------------------

  pauseCampaign: (id) => api.post(`/campaigns/${id}/pause`),

  // --------------------------------------------------
  // RESUME
  // --------------------------------------------------

  resumeCampaign: (id) => api.post(`/campaigns/${id}/resume`),

  // --------------------------------------------------
  // CANCEL
  // --------------------------------------------------

  cancelCampaign: (id) => api.post(`/campaigns/${id}/cancel`),

  // --------------------------------------------------
  // STATS
  // --------------------------------------------------

  getCampaignStats: (id) => api.get(`/campaigns/${id}/stats`),

  // --------------------------------------------------
  // DELETE
  // --------------------------------------------------

  deleteCampaign: (id) => api.delete(`/campaigns/${id}`),
};

export default campaignApi;
